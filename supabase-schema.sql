-- -----------------------------
-- OPTIONAL PROGRESS VIEW
-- -----------------------------
create or replace view public.family_hour_progress
with (security_invoker = true)
as
select
  f.id as family_record_id,
  f.school_id,
  s.school_name,
  f.family_id,
  f.student_name,
  f.grade,
  f.required_hours,
  coalesce(sum(se.hours) filter (where se.status = 'approved'), 0)::numeric(7,2) as approved_hours,
  coalesce(sum(se.hours) filter (where se.status = 'pending'), 0)::numeric(7,2) as pending_hours,
  greatest(
    f.required_hours - coalesce(sum(se.hours) filter (where se.status = 'approved'), 0),
    0
  )::numeric(7,2) as hours_left,
  f.active
from public.families f
join public.schools s on s.id = f.school_id
left join public.service_entries se on se.family_record_id = f.id
group by
  f.id, f.school_id, s.school_name, f.family_id,
  f.student_name, f.grade, f.required_hours, f.active;

grant select on public.family_hour_progress to authenticated;

