on public.service_entries
for select
to authenticated
using (
  submitted_by = auth.uid()
  or public.current_user_role() = 'admin'
);

-- Users and admins may submit their own pending entries.
drop policy if exists "service_entries_insert_own" on public.service_entries;
create policy "service_entries_insert_own"
on public.service_entries
for insert
to authenticated
with check (
  submitted_by = auth.uid()
  and status = 'pending'
  and authorized_by is null
  and authorized_at is null
);

-- Only admins authorize or otherwise update entries.
